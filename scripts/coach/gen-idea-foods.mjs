// Regenerates lib/coach-chat/meal-ideas-foods.ts: the per-100g numbers for every food_id the
// meal-idea dishes use, copied from supabase/seeds/*.csv
// (China Food Composition Table, plus the USDA FoodData Central supplement). Run after adding a dish:
//   node scripts/coach/gen-idea-foods.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const split = (line) => [...line.matchAll(/("([^"]*)"|[^,]*)(,|$)/g)].map((m) => m[2] ?? m[1])
function csv(path) {
  const [header, ...rows] = readFileSync(path, 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/)
  const keys = split(header)
  return new Map(rows.map((line) => {
    const cells = split(line)
    return [Number(cells[0]), Object.fromEntries(keys.map((k, i) => [k, cells[i]]))]
  }))
}
const foods = csv('supabase/seeds/foods_clean.csv')
const nutrition = csv('supabase/seeds/food_nutrition_clean.csv')
// Common foods the Chinese table lacks, from USDA FoodData Central (seed_usda_supplement.sql).
for (const [id, row] of csv('supabase/seeds/foods_usda_supplement.csv')) {
  foods.set(id, row)
  nutrition.set(id, row)
}

const sources = ['lib/coach-chat/meal-ideas.ts', 'lib/coach-chat/meal-ideas-more.ts'].map((p) => readFileSync(p, 'utf8')).join('\n')
const ids = new Set()
for (const m of sources.matchAll(/food: (\d+)/g)) ids.add(Number(m[1]))
for (const m of sources.matchAll(/\bi\('[^']*', (\d+),/g)) ids.add(Number(m[1]))
ids.add(1016).add(821).add(1584) // oil(), rice(), egg() helpers

const lines = [...ids].sort((a, b) => a - b).map((id) => {
  const food = foods.get(id)
  const n = nutrition.get(id)
  if (!food || !n) throw new Error(`food_id ${id} is not in the food library`)
  return `  ${id}: { name: ${JSON.stringify(food.canonical_name)}, kcal: ${Number(n.energy_kcal_100g)}, protein: ${Number(n.protein_g_100g)} },`
})

writeFileSync('lib/coach-chat/meal-ideas-foods.ts', `// GENERATED by scripts/coach/gen-idea-foods.mjs from supabase/seeds/foods_clean.csv and
// food_nutrition_clean.csv. Do not edit by hand: add the dish, then re-run the script.
// tests/coach-chat/meal-ideas.test.ts checks every number against the CSV again.

/** Per-100 g energy (kcal) and protein (g) of every food the meal ideas use. */
export const IDEA_FOODS = {
${lines.join('\n')}
} as const
`)
console.log(`wrote ${ids.size} foods`)
