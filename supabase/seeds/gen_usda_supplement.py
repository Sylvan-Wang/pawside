#!/usr/bin/env python3
"""Writes seed_usda_supplement.sql from foods_usda_supplement.csv (run from the repo root)."""
import csv

rows = list(csv.DictReader(open('supabase/seeds/foods_usda_supplement.csv', encoding='utf-8')))
q = lambda s: "'" + s.replace("'", "''") + "'"
foods = ",\n".join(
    f"  ({r['food_id']}, {q(r['canonical_name'])}, {q(r['category'])}, "
    f"{q('USDA FoodData Central, SR Legacy, fdcId ' + r['fdc_id'] + ': ' + r['usda_description'])})"
    for r in rows)
nutrition = ",\n".join(
    f"  ({r['food_id']}, {r['energy_kcal_100g']}, {r['protein_g_100g']}, {r['fat_g_100g']}, "
    f"{r['carb_g_100g']}, {r['fiber_g_100g']}, {r['sodium_mg_100g']}, 'usda_sr_legacy_2018')"
    for r in rows)

open('supabase/seeds/seed_usda_supplement.sql', 'w', encoding='utf-8').write(f"""-- Seed: common foods missing from the China Food Composition Table import (2026-11-15)
-- GENERATED by supabase/seeds/gen_usda_supplement.py from foods_usda_supplement.csv.
-- Source: USDA FoodData Central, SR Legacy (final release April 2018). Public domain (CC0).
--   Each row's foods.source names its fdcId; every number can be checked at
--   https://fdc.nal.usda.gov/food-details/<fdcId>/nutrients  (values per 100 g, as published)
-- Ids start at 2001 so they never collide with the 1-1697 range of seed_food_data.sql.
-- Safe to re-run: existing rows are left alone.

begin;

insert into foods (id, canonical_name, category, source) values
{foods}
on conflict do nothing;

insert into food_nutrition (food_id, energy_kcal, protein_g, fat_g, carb_g, fiber_g, sodium_mg, data_version) values
{nutrition}
on conflict (food_id) do nothing;

select setval('foods_id_seq', (select max(id) from foods));

commit;
""")
print(f'wrote {len(rows)} foods')
